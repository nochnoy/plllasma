-- ------------------------------------------------------------
-- 1. Индексы tbl_messages
--    ~200k записей, MyISAM: перестроение займёт секунды,
--    таблица будет заблокирована на это время.
-- ------------------------------------------------------------
ALTER TABLE `tbl_messages`
  ADD KEY `idx_place_time` (`id_place`, `time_created`),
  ADD KEY `idx_place_parent` (`id_place`, `id_parent`),
  ADD KEY `idx_first_parent` (`id_first_parent`);

-- Логин по токену делает SELECT по logkey без индекса
ALTER TABLE `tbl_users`
  ADD KEY `idx_logkey` (`logkey`);


-- ------------------------------------------------------------
-- 2. Старая таблица игнора — удаляется
-- ------------------------------------------------------------
DROP TABLE IF EXISTS `lnk_user_ignor`;


-- ------------------------------------------------------------
-- 3. Новая таблица игнора
--
-- Семантика:
--   - mode=1 (soft): запись (A, B) значит «A не хочет видеть
--     подсветку сообщений B». Направленная: (B, A) может
--     существовать независимо.
--   - mode=2 (vanish): пара взаимно исчезает. id_user — инициатор,
--     только он видит ссылку «Вернуться» и может отменить.
--     Запись должна быть ОДНА на пару в любом направлении —
--     уникальность неупорядоченной пары обеспечивается кодом
--     (при «Исчезнуть» все записи пары заменяются одной, mode=2).
--   - uk_pair не даёт дублировать направленную пару; апгрейд
--     soft → vanish делается как UPDATE mode=2.
-- ------------------------------------------------------------
CREATE TABLE `lnk_user_ignore` (
  `id` int NOT NULL AUTO_INCREMENT,
  `id_user` bigint NOT NULL COMMENT 'Инициатор. mode=1: кто игнорит. mode=2: кто нажал «Исчезнуть» (только он может отменить)',
  `id_ignored_user` bigint NOT NULL COMMENT 'Кого игнорируют',
  `mode` tinyint NOT NULL COMMENT '1 = soft (направленный, не подсвечивать сообщения); 2 = vanish (взаимное исчезновение)',
  `date_created` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_pair` (`id_user`, `id_ignored_user`),
  KEY `idx_ignored` (`id_ignored_user`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;


